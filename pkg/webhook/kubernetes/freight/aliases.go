// getAvailableFreightAlias returns a generated alias not already in use by
// any Freight in the cluster. On May 4, by the control plane's local date,
// aliases are composed from an alternate list of nouns.
func (w *webhook) getAvailableFreightAlias(
	ctx context.Context,
) (string, error) {
	generator := w.freightAliasGenerator
	if now := w.nowFn(); now.Month() == time.May && now.Day() == 4 {
		generator = w.mayFourthAliasGenerator
	}
	for {
		alias := generator.Name()
		freight := kargoapi.FreightList{}
		if err := w.client.List(
			ctx,
			&freight,
			client.MatchingLabels{kargoapi.LabelKeyAlias: alias},
		); err != nil {
			return "", fmt.Errorf(
				"error checking for existence of Freight with alias %q: %w",
				alias,
				err,
			)
		}
		if len(freight.Items) == 0 {
			return alias, nil
		}
	}
}

